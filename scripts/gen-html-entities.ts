/**
 * Regenerates `src/summaries/html-entities.ts` from Python's
 * `html.entities.html5` (the WHATWG named character references), keeping the
 * semicolon-terminated names only.
 *
 *   bun scripts/gen-html-entities.ts          # rewrite the module
 *   bun scripts/gen-html-entities.ts --check  # exit 1 when the module differs
 *
 * `src/summaries/html-entities.test.ts` runs the same comparison whenever
 * `python3` is on PATH, so a hand edit to the table is a red test.
 */

const OUT = new URL("../src/summaries/html-entities.ts", import.meta.url).pathname;
const PER_LINE = 40;

/** Python's `html.entities.html5`, or `null` when `python3` is not on PATH. */
export function pythonHtml5Entities(): Record<string, string> | null {
  try {
    const proc = Bun.spawnSync(["python3", "-I", "-c", "import html.entities, json; print(json.dumps(html.entities.html5))"]);
    return proc.exitCode === 0 ? (JSON.parse(proc.stdout.toString()) as Record<string, string>) : null;
  } catch {
    return null;
  }
}

/** The module's whole text for `entities` (Python's dict: `"amp;"` → `"&"`). */
export function renderHtmlEntitiesModule(entities: Record<string, string>): string {
  const pairs = Object.keys(entities)
    .filter((k) => k.endsWith(";"))
    .sort((a, b) => (a < b ? -1 : a > b ? 1 : 0))
    .map((k) => `${k.slice(0, -1)}=${[...entities[k]!].map((ch) => ch.codePointAt(0)!.toString(16)).join(",")}`);
  const lines: string[] = [];
  for (let i = 0; i < pairs.length; i += PER_LINE) lines.push(pairs.slice(i, i + PER_LINE).join(" "));
  const table = lines.map((l, i) => `  ${JSON.stringify(i < lines.length - 1 ? `${l} ` : l)}`).join(" +\n");
  return `/**
 * The HTML5 named character references (WHATWG), the semicolon-terminated
 * forms: every \`name=hex[,hex]\` pair (${pairs.length} names). The legacy forms
 * without a \`;\` stay text. Read through {@link namedEntity}.
 *
 * GENERATED by \`bun scripts/gen-html-entities.ts\` from Python's
 * \`html.entities.html5\`; never edit the table by hand.
 */

const TABLE =
${table};

let map: Map<string, string> | null = null;

/** The text \`&name;\` stands for, or \`undefined\` when HTML5 names no such reference (case-sensitive). */
export function namedEntity(name: string): string | undefined {
  if (!map) {
    map = new Map();
    for (const pair of TABLE.split(" ")) {
      const eq = pair.indexOf("=");
      if (eq <= 0) continue;
      map.set(pair.slice(0, eq), String.fromCodePoint(...pair.slice(eq + 1).split(",").map((x) => Number.parseInt(x, 16))));
    }
  }
  return map.get(name);
}
`;
}

if (import.meta.main) {
  const entities = pythonHtml5Entities();
  if (!entities) {
    console.error("python3 with html.entities is required");
    process.exit(2);
  }
  const text = renderHtmlEntitiesModule(entities);
  if (process.argv.includes("--check")) {
    const same = (await Bun.file(OUT).text()) === text;
    console.log(same ? "html-entities.ts is up to date" : "html-entities.ts differs from the generator");
    process.exit(same ? 0 : 1);
  }
  await Bun.write(OUT, text);
  console.log(`wrote ${OUT}`);
}
