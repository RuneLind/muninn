/**
 * Regenerates `src/summaries/whatwg-encodings.ts` from the WHATWG Encoding
 * Standard: every encoding's labels (`encodings.json`) and the decode table of
 * each single-byte encoding Bun's `TextDecoder` refuses (`index-<name>.txt`).
 *
 *   bun scripts/gen-whatwg-encodings.ts                # fetch from encoding.spec.whatwg.org, rewrite
 *   bun scripts/gen-whatwg-encodings.ts --from <dir>   # read the files from <dir> instead
 *   bun scripts/gen-whatwg-encodings.ts --check        # exit 1 when the module differs
 *
 * `TABLED` is the list Bun 1.3.14 refuses by the encoding's own name (probed
 * 2026-11-22: `new TextDecoder(name)` throws). `whatwg-encodings.test.ts` fails
 * when a single-byte encoding is neither decodable natively nor tabled.
 */

const OUT = new URL("../src/summaries/whatwg-encodings.ts", import.meta.url).pathname;
const BASE = "https://encoding.spec.whatwg.org/";

export const TABLED = [
  "ISO-8859-2",
  "ISO-8859-4",
  "ISO-8859-5",
  "ISO-8859-10",
  "ISO-8859-13",
  "ISO-8859-14",
  "ISO-8859-15",
  "ISO-8859-16",
  "KOI8-R",
  "macintosh",
  "windows-1250",
  "windows-1251",
  "windows-1254",
  "windows-1256",
  "windows-1258",
  "x-mac-cyrillic",
];

interface EncodingGroup {
  heading: string;
  encodings: { name: string; labels: string[] }[];
}

/** The 128 code points of an index file's pointers 0–127 (bytes 0x80–0xFF); a missing pointer is U+FFFD. */
export function parseSingleByteIndex(text: string): string {
  const cps = new Array<number>(128).fill(0xfffd);
  for (const line of text.split("\n")) {
    const m = /^\s*(\d+)\s+0x([0-9A-Fa-f]+)/.exec(line);
    if (m) cps[Number(m[1])] = parseInt(m[2]!, 16);
  }
  return String.fromCodePoint(...cps);
}

/** A string literal with every character that is not a visible letter, digit, mark, punctuation or symbol escaped. */
function literal(s: string): string {
  let out = '"';
  for (const ch of s) {
    if (ch === '"' || ch === "\\") out += "\\" + ch;
    else if (/^[\p{L}\p{M}\p{N}\p{P}\p{S}]$/u.test(ch) && ch !== "­") out += ch;
    else out += "\\u" + ch.codePointAt(0)!.toString(16).toUpperCase().padStart(4, "0");
  }
  return out + '"';
}

export function renderModule(groups: EncodingGroup[], indexes: Record<string, string>): string {
  const labels = groups
    .flatMap((g) => g.encodings)
    .map((e) => `  ${JSON.stringify(e.name)}: ${JSON.stringify(e.labels)},`)
    .join("\n");
  const single = groups.find((g) => g.heading === "Legacy single-byte encodings")!.encodings.map((e) => e.name);
  const tables = TABLED.map((name) => `  ${JSON.stringify(name)}: ${literal(parseSingleByteIndex(indexes[name]!))},`).join("\n");
  return `/**
 * The WHATWG Encoding Standard's labels, and the decode tables of the
 * single-byte encodings Bun's \`TextDecoder\` refuses. Read through
 * \`decoderFor\` (\`safe-fetch.ts\`).
 *
 * GENERATED by \`bun scripts/gen-whatwg-encodings.ts\` from
 * https://encoding.spec.whatwg.org/ (\`encodings.json\` and \`index-<name>.txt\`).
 * Do not edit by hand.
 */

/** Every encoding's name and its labels (lowercase, as the standard lists them). */
export const ENCODING_LABELS: Record<string, readonly string[]> = {
${labels}
};

/** The names under "Legacy single-byte encodings". */
export const SINGLE_BYTE_ENCODINGS: readonly string[] = ${JSON.stringify(single)};

/** Bytes 0x80–0xFF of each tabled encoding, one character each; U+FFFD where the index has no pointer. */
export const SINGLE_BYTE_TABLES: Record<string, string> = {
${tables}
};
`;
}

async function readSource(from: string | null, file: string): Promise<string> {
  if (from) return Bun.file(`${from}/${file}`).text();
  const res = await fetch(BASE + file);
  if (!res.ok) throw new Error(`${file}: HTTP ${res.status}`);
  return res.text();
}

if (import.meta.main) {
  const args = process.argv.slice(2);
  const fromAt = args.indexOf("--from");
  const from = fromAt >= 0 ? args[fromAt + 1]! : null;
  const groups = JSON.parse(await readSource(from, "encodings.json")) as EncodingGroup[];
  const indexes: Record<string, string> = {};
  for (const name of TABLED) indexes[name] = await readSource(from, `index-${name.toLowerCase()}.txt`);
  const text = renderModule(groups, indexes);
  if (args.includes("--check")) {
    const current = await Bun.file(OUT).text();
    if (current !== text) {
      process.stderr.write(`${OUT} differs from the generator's output\n`);
      process.exit(1);
    }
  } else {
    await Bun.write(OUT, text);
  }
}
