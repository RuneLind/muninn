#!/usr/bin/env bun
/**
 * Generates `src/format/diagram-styles.ts` from the archify skill's
 * `template.html`: every CSS rule over an archify semantic class (`c-`, `s-`,
 * `t-`, `a-`, `m-`, `semantic-sigil`, `sigil-fill`), with each archify colour
 * variable replaced by a reader token from {@link TOKEN_MAP}, so a `<Diagram>`
 * follows the reader's light and dark themes. Rules under `svg[data-preset=…]`
 * are skipped: the sanitizer strips `data-preset`.
 *
 *   bun scripts/gen-diagram-styles.ts [template.html]
 *
 * Fails on an archify variable the map does not name, so a template change
 * cannot ship an unthemed colour.
 */
import path from "node:path";
import os from "node:os";

const DEFAULT_TEMPLATE = path.join(os.homedir(), ".claude/skills/archify/assets/template.html");
const OUT = path.join(import.meta.dir, "../src/format/diagram-styles.ts");

const mix = (token: string, pct: number) => `color-mix(in srgb, var(${token}) ${pct}%, var(--bg-surface))`;

/** Archify variable → reader CSS value. */
export const TOKEN_MAP: Readonly<Record<string, string>> = {
  "--text": "var(--text-primary)",
  "--text-muted": "var(--text-secondary)",
  "--text-dim": "var(--text-muted)",
  "--frontend-stroke": "var(--status-cyan)",
  "--frontend-fill": mix("--status-cyan", 14),
  "--backend-stroke": "var(--status-success)",
  "--backend-fill": mix("--status-success", 14),
  "--database-stroke": "var(--status-magenta)",
  "--database-fill": mix("--status-magenta", 14),
  "--cloud-stroke": "var(--status-warning)",
  "--cloud-fill": mix("--status-warning", 12),
  "--security-stroke": "var(--status-error)",
  "--security-fill": mix("--status-error", 12),
  "--messagebus-stroke": "var(--status-tool)",
  "--messagebus-fill": mix("--status-tool", 14),
  "--external-stroke": "var(--text-muted)",
  "--external-fill": mix("--text-muted", 10),
  "--arrow": "var(--text-muted)",
  "--arrow-emphasis": "var(--accent)",
  "--grid": "var(--border-subtle)",
  "--mask": "var(--bg-surface)",
  "--lane-fill": mix("--text-muted", 4),
  "--lane-stroke": "var(--border-secondary)",
};

const CLASS_RE = /\.((?:[csatm]-[a-z][a-z0-9-]*)|semantic-sigil|sigil-fill)\b/g;

export interface DiagramRule {
  selector: string;
  body: string;
}

/** The semantic-class rules of a template's `<style>` blocks, themed. */
export function extractRules(templateHtml: string): { rules: DiagramRule[]; classes: string[] } {
  const css = [...templateHtml.matchAll(/<style[^>]*>([\s\S]*?)<\/style>/g)].map((m) => m[1]).join("\n").replace(/\/\*[\s\S]*?\*\//g, "");
  const rules: DiagramRule[] = [];
  const classes = new Set<string>();
  for (const m of css.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
    const selectors = m[1]!.split(",").map((s) => s.trim()).filter(Boolean);
    const kept = selectors.filter((s) => !s.includes("[data-preset") && /\.(?:[csatm]-[a-z]|semantic-sigil|sigil-fill)/.test(s));
    if (kept.length === 0) continue;
    for (const s of kept) for (const c of s.matchAll(CLASS_RE)) classes.add(c[1]!);
    const body = m[2]!
      .split(";")
      .map((d) => d.trim())
      .filter(Boolean)
      .map((d) =>
        d.replace(/var\((--[a-z0-9-]+)\)/g, (_, v: string) => {
          const to = TOKEN_MAP[v];
          if (!to) throw new Error(`archify variable ${v} has no reader token (selector ${kept[0]})`);
          return to;
        }),
      )
      .join("; ");
    rules.push({ selector: kept.map((s) => s.replace(/^svg\s+/, "")).join(", "), body });
  }
  return { rules, classes: [...classes].sort() };
}

if (import.meta.main) {
  const src = process.argv[2] ?? DEFAULT_TEMPLATE;
  const { rules, classes } = extractRules(await Bun.file(src).text());
  const out = `// GENERATED by scripts/gen-diagram-styles.ts from the archify template.html — do not edit.
/**
 * The archify semantic classes a \`<Diagram>\` SVG may carry, and their rules
 * themed with reader tokens (light and dark follow the reader). A leaf: the
 * sanitizer (\`src/wiki/diagram-svg.ts\`) and the reader stylesheet both read it.
 */

/** Every archify semantic class the template styles (${classes.length}). */
export const DIAGRAM_CLASSES: readonly string[] = ${JSON.stringify(classes, null, 2)};

const RULES: readonly (readonly [string, string])[] = ${JSON.stringify(
    rules.map((r) => [r.selector, r.body]),
    null,
    2,
  )};

/** The rules, each selector scoped under \`scope\` (e.g. \`.wiki-article .dgm-svg\`). */
export function diagramClassStyles(scope: string): string {
  return RULES.map(([sel, body]) => \`\${sel.split(", ").map((s) => \`\${scope} \${s}\`).join(", ")} { \${body}; }\`).join("\\n");
}
`;
  await Bun.write(OUT, out);
  console.log(`rules ${rules.length} classes ${classes.length} → ${path.relative(process.cwd(), OUT)}`);
}
